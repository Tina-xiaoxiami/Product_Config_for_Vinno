import { test, expect } from '@playwright/test'

test('shared combination retains model differences through editing, publication and history', async ({ page }) => {
  const pageErrors = []
  page.on('pageerror', error => pageErrors.push(error.message))
  async function chooseSelect(control, name) {
    await control.click()
    const menu = await control.getByRole('combobox').getAttribute('aria-controls')
    await page.locator(`#${menu}`).getByRole('option', { name, exact: true }).click()
  }
  await page.goto('/probe-config')
  await page.getByRole('button', { name: '新建共同总集', exact: true }).click()
  const create = page.getByRole('dialog', { name: '建立共同总集' })
  await create.getByRole('textbox').first().fill('V系列与ULTIMUS共同总集')
  await create.getByRole('button', { name: '子系列组合', exact: true }).click()
  await page.getByRole('button', { name: 'V系列与ULTIMUS · 3 个机型', exact: true }).click()
  await create.getByRole('button', { name: '建立并核对草稿' }).click()
  await expect(create).not.toBeVisible()
  await expect(page.getByText('3 个机型', { exact: true })).toBeVisible()
  await expect(page.getByText('2 个探头物料 · 1 个功能', { exact: true })).toBeVisible()
  await expect(page.getByRole('button',{name:'编辑 P2 P-2 的 造影',exact:true})).toBeVisible()
  await page.getByRole('button', { name: '编辑 P1 P-1 的 造影', exact: true }).first().click()
  const editor = page.getByRole('dialog', { name: '编辑共同总集' })
  await expect(editor.locator('.el-form-item').filter({ hasText: '定义值支持状态' }).getByRole('combobox')).toBeDisabled()
  await chooseSelect(editor.locator('.el-form-item').filter({ hasText: '现状值支持状态' }).locator('.el-select'), '支持')
  await editor.getByRole('button', { name: '应用到待保存草稿' }).click()
  await page.getByRole('button', { name: '保存草稿', exact: true }).click()
  await expect(page.getByRole('button', { name: '发布预览', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: '发布预览', exact: true }).click()
  const publish = page.getByRole('dialog', { name: '发布探头配置' })
  await publish.getByPlaceholder('业务版本号（留空按配置管理规则递增）').fill('1.2.3')
  await publish.getByPlaceholder('发布说明').fill('共同总集与各机型差异核对')
  await expect(publish.getByRole('button', { name: '重新核对发布预览' })).toBeEnabled()
  await publish.getByRole('button', { name: '重新核对发布预览' }).click()
  await expect(publish.getByText(/将创建配置管理版本/)).toBeVisible()
  await chooseSelect(publish.locator('.el-select').first(), '国内 / VINNO 6')
  await expect(publish.getByText('不适用', { exact: true })).toHaveCount(2)
  await publish.getByRole('button', { name: '确认发布', exact: true }).click()
  await expect(publish).not.toBeVisible()
  await expect(page.getByText('已发布', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '版本历史', exact: true }).click()
  await page.getByRole('button', { name: '查看快照', exact: true }).click()
  await expect(page.getByText(/发布时总集和机型范围/)).toBeVisible()
  const downloading = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出', exact: true }).click()
  expect((await downloading).suggestedFilename()).toContain('1.2.3')
  await page.getByRole('button', { name: '恢复为新草稿', exact: true }).click()
  await page.getByRole('button', { name: '确定', exact: true }).click()
  await expect(page.getByText(/已恢复为草稿/)).toBeVisible()
  await page.getByRole('button', { name: '返回配置', exact: true }).click()
  await expect(page.getByText('待发布草稿', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '编辑 P1 P-1 的 造影', exact: true }).first().click()
  await editor.locator('textarea').fill('第二版共同说明')
  await editor.getByRole('button', { name: '应用到待保存草稿' }).click()
  await page.getByRole('button', { name: '保存草稿', exact: true }).click()
  await page.getByRole('button', { name: '发布预览', exact: true }).click()
  await publish.getByPlaceholder('业务版本号（留空按配置管理规则递增）').fill('1.2.4')
  await expect(publish.getByRole('button', { name: '重新核对发布预览' })).toBeEnabled()
  await publish.getByRole('button', { name: '重新核对发布预览' }).click()
  await expect(publish.getByText(/将创建配置管理版本/)).toBeVisible()
  await publish.getByRole('button', { name: '确认发布', exact: true }).click()
  await expect(publish).not.toBeVisible()
  await page.getByRole('button', { name: '版本历史', exact: true }).click()
  await expect(page.getByRole('cell', { name: '1.2.4', exact: true })).toBeVisible()
  expect(pageErrors).toEqual([])
})
