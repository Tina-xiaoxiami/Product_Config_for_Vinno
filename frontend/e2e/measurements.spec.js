test('imports human measurements, searches both UI names and filters modes and applications', async ({ page }) => {
  page.setDefaultTimeout(10000)
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  // Element Plus draws a visible label over its native radio/checkbox input.
  async function choose(control, checked = true) {
    if (await control.isChecked() !== checked) await control.locator('..').click()
    if (checked) await expect(control).toBeChecked()
    else await expect(control).not.toBeChecked()
  }
  await page.goto('/measurements')
  await page.getByRole('button', { name: '导入人用中文表', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '导入人用测量库' })
  await dialog.getByLabel('来源版本').fill('1.51.90-test')
  await dialog.getByLabel('人用中文表').setInputFiles(fileURLToPath(new URL('./fixtures/measurement-human.xlsx', import.meta.url)))
  await dialog.getByRole('button', { name: '导入', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByText('7 / 7 条', { exact: true })).toBeVisible()
  const classification = page.getByRole('radiogroup', { name: '测量分类' })
  const recordType = page.getByRole('radiogroup', { name: '记录类型' })
  const parentBox = await classification.boundingBox()
  const childBox = await recordType.boundingBox()
  expect(parentBox.y + parentBox.height, 'classification sits above navigation and results').toBeLessThanOrEqual(childBox.y)
  await expect(page.locator('.measurement-library .source-line')).toHaveCount(0)
  await choose(recordType.getByRole('radio', { name: '计算项', exact: true }))
  await expect(page.getByText('2 / 2 条', { exact: true })).toBeVisible()
  await choose(classification.getByRole('radio', { name: '常规测量', exact: true }))
  await expect(recordType.getByRole('radio', { name: '全部', exact: true })).toBeChecked()
  await expect(recordType.getByRole('radio', { name: '计算项', exact: true })).toBeEnabled()
  await expect(page.getByText('3 / 3 条', { exact: true })).toBeVisible()
  await choose(recordType.getByRole('radio', { name: '测量项', exact: true }))
  await choose(classification.getByRole('radio', { name: '应用测量', exact: true }))
  await expect(recordType.getByRole('radio', { name: '全部', exact: true })).toBeChecked()
  await expect(page.getByText('1 / 1 条', { exact: true })).toBeVisible()
  await choose(classification.getByRole('radio', { name: '全部分类', exact: true }))
  await expect(recordType.getByRole('radio', { name: '计算项', exact: true })).toBeEnabled()
  await expect(page.getByText('7 / 7 条', { exact: true })).toBeVisible()
  await choose(classification.getByRole('radio', { name: '未分类', exact: true }))
  await choose(recordType.getByRole('radio', { name: '计算项', exact: true }))
  await expect(page.getByText('2 / 2 条', { exact: true })).toBeVisible()
  await choose(classification.getByRole('radio', { name: '全部分类', exact: true }))
  await expect(page.getByText('7 / 7 条', { exact: true })).toBeVisible()

  await expect(page.getByRole('cell', { name: 'Distance', exact: true }).first()).toBeVisible()
  const search = page.getByPlaceholder('查找 Id、英文 UI 或中文 UI 名称')
  await search.fill('膀胱')
  await expect(page.getByText('1 / 1 条', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '详情', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '测量记录详情' })).toContainText('Bladder Vol.')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog', { name: '测量记录详情' })).not.toBeVisible()
  await search.clear()
  await choose(page.getByRole('radio', { name: '应用测量', exact: true }))
  await expect(page.getByText('1 / 1 条', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '筛选应用', exact: true }).click()
  const popover = page.locator('.el-popover:visible')
  await popover.getByRole('button', { name: '清空搜索结果' }).click()
  await choose(popover.getByRole('checkbox', { name: 'GYN', exact: true }))
  await popover.getByRole('button', { name: '应用', exact: true }).click()
  await expect(page.getByText('1 / 1 条', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '清除查询条件', exact: true }).click()
  await choose(page.getByRole('radio', { name: '常规测量', exact: true }))
  await page.getByRole('button', { name: '筛选关联模式', exact: true }).click()
  await popover.getByRole('button', { name: '清空搜索结果' }).click()
  await choose(popover.getByRole('checkbox', { name: 'Doppler', exact: true }))
  await search.click()
  await expect(page.getByText('1 / 3 条', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '筛选关联模式', exact: true }).click()
  await page.getByRole('button', { name: '清除筛选', exact: true }).click()
  await expect(page.getByText('3 / 3 条', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '筛选Id', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '列设置', exact: true }).click()
  const columns = page.getByRole('dialog', { name: '列设置', exact: true })
  await choose(columns.getByRole('checkbox', { name: '显示Id', exact: true }), false)
  await columns.getByRole('button', { name: '应用', exact: true }).click()
  await page.reload()
  await expect(page.getByRole('button', { name: '筛选Id', exact: true })).toHaveCount(0)
  await search.fill('no-such-measurement')
  await expect(page.getByText('当前条件未命中', { exact: true })).toBeVisible()
  expect(errors).toEqual([])
})

test('measurement controls stay compact and the table fills remaining height through resize', async ({ page }, testInfo) => {
  page.setDefaultTimeout(10000)
  const buffer = await readFile(fileURLToPath(new URL('./fixtures/measurement-layout.xlsx', import.meta.url)))
  const imported = await page.request.post('/api/measurements/import', { multipart: {
    version: 'layout-check', file: { name: 'measurement-layout.xlsx', mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', buffer }
  } })
  expect(imported.ok()).toBe(true)
  await page.setViewportSize({ width: 1800, height: 1000 })
  await page.goto('/measurements')
  await expect(page.getByText('87 / 87 条', { exact: true })).toBeVisible()
  const search = page.getByPlaceholder('查找 Id、英文 UI 或中文 UI 名称')
  const version = page.getByRole('combobox', { name: '来源批次' })
  const searchBox = await page.locator('.search-input > .el-input__wrapper').boundingBox()
  const versionBox = await page.locator('.batch-select .el-select__wrapper').boundingBox()
  expect(Math.abs(searchBox.y + searchBox.height / 2 - versionBox.y - versionBox.height / 2), 'search and version share the first row').toBeLessThan(4)
  expect(searchBox.x).toBeLessThan(versionBox.x)
  expect(searchBox.height).toBe(38)
  expect(searchBox.width).toBeGreaterThanOrEqual(440)
  expect(versionBox.height).toBe(32)
  expect((await page.getByRole('button', { name: '导入人用中文表', exact: true }).boundingBox()).height).toBe(32)
  expect((await page.getByRole('button', { name: '筛选中文 UI 名称', exact: true }).boundingBox()).height).toBe(24)
  const applicationsColumn = await page.locator('.application-filter-column').boundingBox()
  const modesColumn = await page.locator('.mode-filter-column').boundingBox()
  await expect(page.getByRole('navigation', { name: '应用筛选导航', exact: true }).getByText('应用', { exact: true })).toBeVisible()
  await expect(page.getByRole('navigation', { name: '模式筛选导航', exact: true }).getByText('关联模式', { exact: true })).toBeVisible()
  expect(Math.abs(applicationsColumn.y - modesColumn.y), 'application and mode columns start together').toBeLessThan(2)
  expect(modesColumn.x, 'modes sit in a separate column beside applications').toBeGreaterThanOrEqual(applicationsColumn.x + applicationsColumn.width)

  async function expectFilledTable() {
    const table = await page.locator('.measurement-library .el-table').boundingBox()
    const content = await page.locator('.workspace-content').boundingBox()
    const pagination = await page.locator('.measurement-library .el-pagination').boundingBox()
    expect(table.height).toBeGreaterThan(200)
    expect(pagination.y + pagination.height).toBeLessThanOrEqual(content.y + content.height)
    expect(content.y + content.height - pagination.y - pagination.height, 'bottom whitespace stays within panel padding').toBeLessThan(30)
  }
  await expectFilledTable()
  const statistics = page.getByRole('button', { name: /统计与导入核对/ })
  const scope = page.getByRole('radiogroup', { name: '测量分类' })
  const statisticsBox = await statistics.boundingBox()
  const scopeBox = await scope.boundingBox()
  const kindBox = await page.getByRole('radiogroup', { name: '记录类型' }).boundingBox()
  expect(scopeBox.y + scopeBox.height, 'classification sits in the top toolbar').toBeLessThanOrEqual(kindBox.y)
  expect(Math.abs(statisticsBox.y + statisticsBox.height / 2 - kindBox.y - kindBox.height / 2), 'statistics share the secondary row').toBeLessThan(8)
  await statistics.click()
  await expect(page.getByText('计算启用状态', { exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByText('计算启用状态', { exact: true })).not.toBeVisible()
  await expect(statistics).toBeFocused()
  await expectFilledTable()
  await page.screenshot({ path: testInfo.outputPath('measurement-compact-wide.png') })
  await page.getByRole('button', { name: '下一页', exact: true }).click()
  await expect(page.getByRole('cell', { name: '测量 79', exact: true })).toBeVisible()
  await page.setViewportSize({ width: 1000, height: 760 })
  const narrowApplications = await page.locator('.application-filter-column').boundingBox()
  const narrowModes = await page.locator('.mode-filter-column').boundingBox()
  expect(narrowModes.x).toBeGreaterThanOrEqual(narrowApplications.x + narrowApplications.width)
  await expect.poll(async () => (await page.locator('.measurement-library .el-table').boundingBox()).height).toBeGreaterThan(200)
  await expectFilledTable()
  await page.screenshot({ path: testInfo.outputPath('measurement-compact-narrow.png') })
  await page.setViewportSize({ width: 800, height: 900 })
  const stackedApplications = await page.locator('.application-filter-column').boundingBox()
  const stackedModes = await page.locator('.mode-filter-column').boundingBox()
  const filterPanel = await page.locator('.measurement-filter-sidebar').boundingBox()
  const resultsPanel = await page.locator('.measurement-library .table-region').boundingBox()
  expect(stackedModes.x).toBeGreaterThanOrEqual(stackedApplications.x + stackedApplications.width)
  expect(resultsPanel.y, 'small windows put the two-column filter panel above results').toBeGreaterThanOrEqual(filterPanel.y + filterPanel.height)
  await page.screenshot({ path: testInfo.outputPath('measurement-compact-stacked.png') })
})

test('flat application and mode facets combine, keep empty choices and reset together', async ({ page }, testInfo) => {
  const buffer = await readFile(fileURLToPath(new URL('./fixtures/measurement-human.xlsx', import.meta.url)))
  const imported = await page.request.post('/api/measurements/import', { multipart: {
    version: 'sidebar-check', file: { name: 'measurement-human.xlsx', mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', buffer }
  } })
  expect(imported.ok()).toBe(true)
  await page.setViewportSize({ width: 1500, height: 960 })
  await page.goto('/measurements')
  const sidebar = page.getByRole('complementary', { name: '测量库筛选', exact: true })
  const applications = sidebar.getByRole('group', { name: '具体应用', exact: true })
  const modes = sidebar.getByRole('group', { name: '关联模式', exact: true })
  const choose = async (control, checked = true) => {
    if (await control.isChecked() !== checked) await control.locator('..').click()
    if (checked) await expect(control).toBeChecked()
    else await expect(control).not.toBeChecked()
  }
  await expect(page.getByText('7 / 7 条', { exact: true })).toBeVisible()
  await choose(applications.getByRole('checkbox', { name: 'GYN', exact: true }))
  await expect(page.getByRole('radiogroup', { name: '测量分类' }).getByRole('radio', { name: '应用测量', exact: true })).toBeChecked()
  await choose(applications.getByRole('checkbox', { name: 'ABD', exact: true }))
  await expect(page.getByText('1 / 1 条', { exact: true })).toBeVisible()
  await choose(modes.getByRole('checkbox', { name: 'Tissue', exact: true }))
  await choose(modes.getByRole('checkbox', { name: 'Doppler', exact: true }))
  await expect(page.getByText('1 / 1 条', { exact: true })).toBeVisible()
  await choose(modes.getByRole('checkbox', { name: 'Tissue', exact: true }), false)
  await expect(page.getByText('当前条件未命中', { exact: true })).toBeVisible()
  await expect(applications.getByRole('checkbox', { name: 'GYN', exact: true })).toBeChecked()
  await expect(modes.getByRole('checkbox', { name: 'Tissue', exact: true }).locator('..')).toBeVisible()
  await sidebar.getByRole('button', { name: '不限模式', exact: true }).click()
  await expect(page.getByText('1 / 1 条', { exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('measurement-compact-sidebar.png') })
  await page.getByRole('button', { name: '刷新', exact: true }).click()
  await expect(applications.getByRole('checkbox', { name: 'GYN', exact: true })).toBeChecked()
  await expect(page.getByText('1 / 1 条', { exact: true })).toBeVisible()
  await choose(page.getByRole('radiogroup', { name: '测量分类' }).getByRole('radio', { name: '常规测量', exact: true }))
  await expect(applications.getByRole('checkbox', { name: 'GYN', exact: true })).not.toBeChecked()
  await expect(page.getByText('3 / 3 条', { exact: true })).toBeVisible()
  await choose(modes.getByRole('checkbox', { name: '未标注模式', exact: true }))
  await expect(page.getByText('当前条件未命中', { exact: true })).toBeVisible()
  await page.locator('.query-controls').getByRole('button', { name: '清除查询条件', exact: true }).click()
  await expect(page.getByText('7 / 7 条', { exact: true })).toBeVisible()
  await expect(modes.getByRole('checkbox', { name: '未标注模式', exact: true })).not.toBeChecked()
})
