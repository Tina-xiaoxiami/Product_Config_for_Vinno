import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

test('measurement drafts keep the initial display frozen and publish names, dictionaries, relations and new items', async ({ page }, testInfo) => {
  page.setDefaultTimeout(10000)
  await page.setViewportSize({ width: 1800, height: 1100 })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const buffer = await readFile(fileURLToPath(new URL('./fixtures/measurement-human.xlsx', import.meta.url)))
  const imported = await page.request.post('/api/measurements/import', { multipart: {
    version: 'measurement-workspace-browser', file: { name: 'measurement-human.xlsx', mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', buffer }
  } })
  expect(imported.ok()).toBe(true)
  const batchId = (await imported.json()).batch_id
  const rawLibrary = await (await page.request.get(`/api/measurements?batch_id=${batchId}`)).json()
  const calculation = rawLibrary.entries.find(row => row.kind === 'calculation')
  const candidate = await page.request.post('/api/measurements/enrichment/import', { data: {
    batch_id: batchId, expected_sha256: rawLibrary.batch.sha256, expected_version: rawLibrary.batch.version, schema_version: 1,
    candidates: [{ item_id: calculation.item_id, payload: { categories: ['CARD'], modes: ['Tissue', 'Doppler'], input_terms: [],
      formula_reference: '仅用于隔离版本回归', sources: [{ url: 'https://www.asecho.org/', title: '测试资料', locator: '隔离测试', supports: ['测试'] }],
      uncertainties: ['人工待核对'], research_status: 'proposed', mapping_basis: 'test_fixture' } }]
  } })
  expect(candidate.ok()).toBe(true)
  const sourceBefore = await (await page.request.get(`/api/measurements?batch_id=${batchId}`)).json()
  await page.route('**/api/measurement-workspace?batch_id=*', async route => { await new Promise(resolve => setTimeout(resolve, 200)); await route.continue() })
  await page.goto('/measurements')
  await expect(page.getByRole('button', { name: '发布版本', exact: true })).toBeVisible()
  const fetchWorkspace = async () => (await (await page.request.get(`/api/measurement-workspace?batch_id=${batchId}`)).json())
  let workspace = await fetchWorkspace()
  const initialId = workspace.versions[0].id
  const initial = await (await page.request.get(`/api/measurement-workspace/${workspace.id}/versions/${initialId}`)).json()
  const initialCalc = initial.data.entries.find(row => row.kind === 'calculation' && row.item_id === calculation.item_id)
  expect(initialCalc.categories).toContain('CARD')
  expect(initialCalc.enrichment.status).toBe('pending')
  expect(initialCalc.enrichment.confirmed_payload).toBeNull()

  const search = page.getByPlaceholder('查找 Id、英文 UI 或中文 UI 名称')
  await search.fill('Distance')
  await page.getByRole('button', { name: '编辑', exact: true }).first().click()
  await page.getByRole('menuitem', { name: '编辑名称', exact: true }).click()
  const rename = page.getByRole('dialog', { name: '编辑同类型同 Id 的全库名称', exact: true })
  await rename.getByRole('textbox', { name: '中文 UI 名称', exact: true }).fill('距离（维护版）')
  await rename.getByRole('textbox', { name: '英文 Description', exact: true }).fill('Distance maintained')
  await rename.getByRole('button', { name: '保存到草稿', exact: true }).click()
  await expect(rename).not.toBeVisible()
  workspace = await fetchWorkspace()
  expect(workspace.has_draft).toBe(true)
  const distanceRows = workspace.data.entries.filter(row => row.kind === 'measurement' && row.item_id === 'Distance')
  expect(distanceRows.length).toBeGreaterThan(1)
  expect(distanceRows.every(row => row.cn_name === '距离（维护版）' && row.description === 'Distance maintained')).toBe(true)
  expect(workspace.published_data.entries.some(row => row.cn_name === '距离（维护版）')).toBe(false)

  async function addDictionary(menuName, code, name) {
    await page.getByRole('button', { name: '管理 ▾', exact: true }).click()
    await page.getByRole('menuitem', { name: menuName, exact: true }).click()
    const dialog = page.getByRole('dialog').filter({ has: page.getByRole('textbox', { name: '字典代码', exact: true }) })
    await dialog.getByRole('textbox', { name: '字典代码', exact: true }).fill(code)
    await dialog.getByRole('textbox', { name: '字典显示名称', exact: true }).fill(name)
    await dialog.getByRole('button', { name: '保存到草稿', exact: true }).click()
    await expect(page.getByText('已保存到测量库草稿', { exact: true }).last()).toBeVisible()
    await dialog.getByRole('button', { name: '关闭', exact: true }).click()
    const unsaved = page.getByRole('dialog', { name: '未保存的测量库编辑', exact: true })
    if (await unsaved.isVisible()) await unsaved.getByRole('button', { name: '放弃输入', exact: true }).click()
    await expect(dialog).not.toBeVisible()
  }
  await search.clear()
  await addDictionary('应用字典', 'RESEARCH', '研究应用')
  await addDictionary('模式字典', 'ResearchMode', '研究模式')
  await search.fill('Distance')
  await page.getByRole('button', { name: '编辑', exact: true }).first().click()
  await page.getByRole('menuitem', { name: '编辑关联', exact: true }).click()
  const association = page.getByRole('dialog', { name: '编辑当前关系的应用与模式', exact: true })
  for (const [label, option] of [['编辑应用', '研究应用 (RESEARCH)'], ['编辑关联模式', '研究模式 (ResearchMode)']]) {
    await association.getByRole('combobox', { name: label, exact: true }).click()
    await page.getByRole('option', { name: option, exact: true }).click()
    await association.locator('.el-dialog__header').click()
  }
  await association.getByRole('button', { name: '保存到草稿', exact: true }).click()
  await expect(association).not.toBeVisible()
  workspace = await fetchWorkspace()
  const changedRelations = workspace.data.entries.filter(row => row.kind === 'measurement' && row.item_id === 'Distance' && row.categories.includes('RESEARCH'))
  expect(changedRelations).toHaveLength(1)
  expect(changedRelations[0].mode).toContain('ResearchMode')
  await search.clear()
  await page.getByRole('button', { name: '管理 ▾', exact: true }).click()
  await page.getByRole('menuitem', { name: '新增项目 / 关系', exact: true }).click()
  const added = page.getByRole('dialog').filter({ has: page.getByRole('textbox', { name: '新增 Id', exact: true }) })
  await added.getByRole('textbox', { name: '新增 Id', exact: true }).fill('NewMeasurement')
  await added.getByRole('textbox', { name: '中文 UI 名称', exact: true }).fill('新增测量示例')
  await added.getByRole('textbox', { name: '英文 Description', exact: true }).fill('New measurement')
  async function chooseOption(label, option) {
    await added.getByRole('combobox', { name: label, exact: true }).click()
    await page.getByRole('option', { name: option, exact: true }).click()
    await added.getByRole('textbox', { name: '新增 Id', exact: true }).click()
  }
  await chooseOption('编辑应用', '研究应用 (RESEARCH)')
  await chooseOption('编辑关联模式', '研究模式 (ResearchMode)')
  await added.getByRole('button', { name: '保存到草稿', exact: true }).click()
  await expect(added).not.toBeVisible()
  await search.fill('NewMeasurement')
  await expect(page.getByRole('cell', { name: '新增测量示例', exact: true })).toBeVisible()
  workspace = await fetchWorkspace()
  const manual = workspace.data.entries.find(row => row.item_id === 'NewMeasurement')
  expect(manual.source_entry_id).toBeNull()
  expect(manual.categories).toEqual(['RESEARCH'])
  expect(manual.mode).toEqual(['ResearchMode'])

  await page.getByRole('button', { name: '发布版本', exact: true }).click()
  const publish = page.getByRole('dialog').filter({ has: page.getByRole('textbox', { name: '发布版本号', exact: true }) })
  await publish.getByRole('textbox', { name: '发布版本号', exact: true }).fill('1.51.91-test')
  await publish.getByRole('textbox', { name: '发布版本说明', exact: true }).fill('名称联动、字典及新增项目回归')
  await publish.getByRole('button', { name: '生成发布预览', exact: true }).click()
  await expect(publish.getByRole('button', { name: '确认发布 1.51.91-test', exact: true })).toBeEnabled()
  await publish.screenshot({ path: testInfo.outputPath('measurement-workspace-publish.png') })
  await publish.getByRole('button', { name: '确认发布 1.51.91-test', exact: true }).click()
  await expect(publish).not.toBeVisible()
  workspace = await fetchWorkspace()
  expect(workspace.has_draft).toBe(false)
  expect(workspace.versions).toHaveLength(2)
  const currentId = workspace.versions.find(version => version.version_number === '1.51.91-test').id
  const comparison = await (await page.request.get(`/api/measurement-workspace/${workspace.id}/compare?from_version_id=${initialId}&to_version_id=${currentId}`)).json()
  expect(comparison.changes.some(change => change.entity === 'dictionary')).toBe(true)
  expect(comparison.changes.some(change => change.change_type === 'create' && change.entity === 'item')).toBe(true)
  expect((await (await page.request.get(`/api/measurement-workspace/${workspace.id}/versions/${initialId}`)).json()).data).toEqual(initial.data)
  expect((await (await page.request.get(`/api/measurements?batch_id=${batchId}`)).json()).entries).toEqual(sourceBefore.entries)
  await search.clear()
  await page.screenshot({ path: testInfo.outputPath('measurement-workspace-current.png') })
  await page.getByRole('combobox', { name: '测量库版本', exact: true }).click()
  await page.getByRole('option', { name: new RegExp('^measurement-workspace-browser · ') }).click()
  await expect(page.getByText('历史快照 · 只读', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '编辑', exact: true })).toHaveCount(0)
  await page.screenshot({ path: testInfo.outputPath('measurement-workspace-initial.png') })
  await page.getByRole('button', { name: '版本历史 / 对比', exact: true }).click()
  const history = page.getByRole('dialog', { name: '版本历史与对比', exact: true })
  await history.getByRole('row').filter({ hasText: 'measurement-workspace-browser' }).getByRole('button', { name: '恢复为草稿', exact: true }).click()
  await page.getByRole('dialog', { name: '恢复历史为草稿', exact: true }).getByRole('button', { name: '恢复为草稿', exact: true }).click()
  workspace = await fetchWorkspace()
  expect(workspace.has_draft).toBe(true)
  expect(workspace.data.entries.some(row => row.item_id === 'NewMeasurement')).toBe(false)
  expect(workspace.published_data.entries.some(row => row.item_id === 'NewMeasurement')).toBe(true)
  expect(workspace.changes.some(change => change.change_type === 'delete')).toBe(true)
  expect(errors).toEqual([])
})
