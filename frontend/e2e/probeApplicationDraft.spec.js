import { test, expect } from '@playwright/test'

test('application associations autosave across reload and keep publication separate with scoped actions', async ({page}) => {
  const appResponse=await page.request.post('/api/applications',{data:{name:'草稿回归应用',en_name:'Draft test',sort_order:0}})
  expect(appResponse.ok()).toBe(true)
  const app=(await appResponse.json())
  const categoryResponse=await page.request.post('/api/probe-categories',{data:{name:'草稿回归类别',sort_order:100}})
  expect(categoryResponse.ok()).toBe(true)
  const category=await categoryResponse.json()
  const association=await page.request.post('/api/applications/associations/batch',{data:{changes:[{action:'add',category_id:1,application_id:app.id,probe_type:'regular'}]}})
  expect(association.ok()).toBe(true)
  const before=(await (await page.request.get('/api/applications/versions')).json()).length
  await page.goto('/probe-models')
  const applications=page.getByRole('region',{name:'类别应用',exact:true})
  const models=page.getByRole('region',{name:'探头型号',exact:true})
  await expect(page.locator('.panel-left .panel-header').getByRole('button',{name:'新增类别',exact:true})).toBeVisible()
  await expect(models.getByRole('button',{name:'新增型号',exact:true})).toBeVisible()
  await expect(models.getByRole('button',{name:'从配置补齐变体',exact:true})).toBeVisible()
  await expect(page.locator('#probe-management-actions').getByRole('button',{name:'新增型号',exact:true})).toHaveCount(0)
  await models.getByRole('button',{name:'批量变体 ▾',exact:true}).click()
  await expect(page.getByRole('button',{name:'导出所有变体',exact:true})).toBeVisible()
  await expect(page.locator('.bulk-variant-actions button').filter({hasText:'导入所有变体'})).toBeVisible()
  await page.keyboard.press('Escape')
  await applications.getByRole('button',{name:'编辑应用',exact:true}).click()
  await applications.locator('.app-tag').filter({hasText:'草稿回归应用'}).getByRole('button',{name:'移除',exact:true}).click()
  await expect(applications.getByRole('status')).toContainText('本机草稿已自动保存 · 1 项')
  await page.reload()
  await expect(applications.getByRole('status')).toContainText('本机草稿已自动保存 · 1 项')
  await expect(applications.locator('.app-tag').filter({hasText:'草稿回归应用'})).toHaveCount(0)
  await expect(applications.locator('.pending-item')).toContainText('草稿回归应用')
  expect((await (await page.request.get('/api/applications/versions')).json()).length).toBe(before)
  const official=await (await page.request.get('/api/probe-categories/1/apps')).json()
  expect(official.regular.some(item=>item.id===app.id)).toBe(true)
  await page.locator('.panel-left .category-item').filter({hasText:category.name}).click()
  await page.getByRole('button',{name:'刷新',exact:true}).click()
  await expect(page.locator('.panel-left .category-item.active')).toContainText(category.name)
  await page.reload()
  await expect(page.locator('.panel-left .category-item.active')).toContainText(category.name)
  await expect(applications.getByRole('status')).toContainText('1 项')
  await applications.getByRole('button',{name:'废弃全部',exact:true}).click()
  await page.reload()
  await expect(applications.getByRole('button',{name:'编辑应用',exact:true})).toBeVisible()
  expect((await (await page.request.get('/api/applications/versions')).json()).length).toBe(before)
})

test('publication and cleanup failure remain distinct and an old local draft cannot create another version',async({page})=>{
  const response=await page.request.post('/api/applications',{data:{name:'清理失败回归应用',en_name:'Cleanup test'}})
  expect(response.ok()).toBe(true)
  const before=(await (await page.request.get('/api/applications/versions')).json()).length
  await page.addInitScript(()=>{
    const remove=Storage.prototype.removeItem
    Storage.prototype.removeItem=function(key){
      if(key==='probe-application-associations-draft-v1'&&!window.allowDraftCleanup)throw new Error('simulated cleanup failure')
      return remove.call(this,key)
    }
  })
  await page.goto('/probe-models')
  const scope=page.getByRole('region',{name:'类别应用',exact:true})
  await scope.locator('.add-section .el-select').click()
  await page.getByRole('option',{name:'清理失败回归应用',exact:true}).click()
  await scope.getByRole('button',{name:'添加',exact:true}).click()
  await expect(scope.getByRole('status')).toContainText('本机草稿已自动保存 · 1 项')
  await scope.getByRole('button',{name:'提交并创建版本',exact:true}).click()
  await expect(scope.getByRole('alert').filter({hasText:'服务器已提交'})).toBeVisible()
  await expect(scope.getByRole('button',{name:'重试清理本机草稿',exact:true})).toBeVisible()
  await expect(scope.getByRole('button',{name:'提交并创建版本',exact:true})).toBeDisabled()
  await expect(scope.locator('.app-tag').filter({hasText:'清理失败回归应用'})).toHaveCount(1)
  expect((await (await page.request.get('/api/applications/versions')).json()).length).toBe(before+1)
  await page.reload()
  await expect(scope.locator('.app-tag').filter({hasText:'清理失败回归应用'})).toHaveCount(1)
  await scope.getByRole('button',{name:'提交并创建版本',exact:true}).click()
  expect((await (await page.request.get('/api/applications/versions')).json()).length).toBe(before+1)
  await page.evaluate(()=>{window.allowDraftCleanup=true})
  await scope.getByRole('button',{name:'废弃全部',exact:true}).click()
  await page.reload()
  await expect(scope.getByRole('button',{name:'编辑应用',exact:true})).toBeVisible()
})
