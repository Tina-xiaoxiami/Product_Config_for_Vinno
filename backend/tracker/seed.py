def _normalize(raw: tuple[Any, ...]) -> dict[str, Any]:
    cn, en, category, *rest = raw
    term: dict[str, Any] = {"cn": cn, "en": en, "category": category}
    if rest:
        children = rest[0]
        term["children"] = [{"cn": child_cn, "en": child_en} for child_cn, child_en in children]
        term["needs_review"] = bool(rest[1]) if len(rest) > 1 else False
    return term


